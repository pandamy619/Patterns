"""Сколько подстрок строки s являются анаграммами строки t.

Приём: fixed window (окно фиксированной длины) + частотная таблица,
которая обновляется за O(1) при каждом сдвиге.
Аналог: LeetCode 438 (там просят начальные индексы, здесь — их количество).
"""

from collections import Counter


def substring_anagrams(s: str, t: str) -> int:
    """Количество позиций, с которых в s начинается анаграмма t.
    Одинаковые по содержимому подстроки на разных позициях считаются отдельно.
    Для пустой t ответ 0.

    Время O(n + m), где n = len(s), m = len(t), — без множителя на размер
    алфавита. Память O(u), где u — число различных символов в s и t
    (для строчной латиницы — не больше 26, то есть O(1)).
    """
    width = len(t)
    if width == 0 or width > len(s):
        return 0

    # debt[ch] — сколько символов ch окну ещё НЕ ХВАТАЕТ до анаграммы.
    # Отрицательное значение — символ в избытке. Окно является анаграммой
    # ровно тогда, когда все долги нулевые.
    debt = Counter(t)
    # Число символов с ненулевым долгом. Благодаря ему не нужно на каждом
    # шаге сравнивать таблицы целиком.
    unsettled = len(debt)
    found = 0

    for right, incoming in enumerate(s):
        # Символ вошёл в окно: его долг уменьшается.
        # Долг мог как погаситься (1 -> 0), так и появиться (0 -> -1).
        if debt[incoming] == 0:
            unsettled += 1
        debt[incoming] -= 1
        if debt[incoming] == 0:
            unsettled -= 1

        # Окно переросло нужную ширину — выпускаем самый левый символ.
        left = right - width
        if left >= 0:
            outgoing = s[left]
            if debt[outgoing] == 0:
                unsettled += 1
            debt[outgoing] += 1
            if debt[outgoing] == 0:
                unsettled -= 1

        # Пока окно не набрало ширину, долги погаситься не могут:
        # сумма долгов равна width минус текущая длина окна.
        if unsettled == 0:
            found += 1
    return found
