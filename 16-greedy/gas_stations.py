"""Кольцевой маршрут с заправками: с какой станции стартовать.

Приём: reset on failure (сброс кандидата при провале) — если от кандидата
не доехали до станции f, стартовать с любой станции между ними бессмысленно,
следующий кандидат — f + 1.
Аналог: LeetCode 134 (Gas Station).
"""


def gas_stations(gas: list[int], cost: list[int]) -> int:
    """Вернуть индекс станции, с которой можно проехать полный круг, или -1.

    gas[i] — сколько топлива дают на станции i, cost[i] — сколько уходит
    на перегон от i к (i + 1) % n. Бак вначале пуст, вместимость не ограничена.
    Если подходящих станций несколько, возвращается наименьший индекс.

    Время O(n), память O(1).
    """
    if len(gas) != len(cost):
        raise ValueError("gas и cost должны быть одной длины")
    if not gas:
        return -1

    total = 0      # баланс всего круга: от старта он не зависит
    tank = 0       # бак, если ехать от текущего кандидата
    candidate = 0
    for station, (gained, spent) in enumerate(zip(gas, cost)):
        delta = gained - spent
        total += delta
        tank += delta
        if tank < 0:
            # От candidate до station доехали с неотрицательным баком и всё
            # равно не хватило. Старт с любой промежуточной станции означал бы
            # тот же путь, но без накопленного запаса, — не хватит тем более.
            candidate = station + 1
            tank = 0

    # Топлива на круг не хватает в принципе — старт ничего не изменит.
    if total < 0:
        return -1
    # Иначе последний кандидат гарантированно годится (обоснование в README),
    # и при total >= 0 он всегда меньше n.
    return candidate
