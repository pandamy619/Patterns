"""Правильная скобочная последовательность из трёх видов скобок.

Приём: matching pairs (парные элементы) — стек хранит открытые скобки,
которые ещё ждут свою пару.
Аналог: LeetCode 20.
"""

# Ключ — закрывающая скобка, значение — какая открывающая ей положена.
_OPENER_FOR = {")": "(", "]": "[", "}": "{"}
_OPENERS = frozenset(_OPENER_FOR.values())


def valid_parenthesis_expression(text: str) -> bool:
    """Проверить, что каждая скобка закрыта скобкой своего вида и в свой черёд.

    Символы, не являющиеся скобками, пропускаются. Пустая строка корректна.
    Время O(n), память O(n).
    """
    waiting: list[str] = []  # открытые скобки, ещё не дождавшиеся пары
    for symbol in text:
        if symbol in _OPENERS:
            waiting.append(symbol)
        elif symbol in _OPENER_FOR:
            # Закрыть можно только ту скобку, что открыта последней:
            # всё, что открыто внутри неё, обязано закончиться раньше.
            if not waiting or waiting.pop() != _OPENER_FOR[symbol]:
                return False
    # Остались незакрытые — например, "((" — тоже ошибка.
    return not waiting
