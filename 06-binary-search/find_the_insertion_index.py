"""Индекс вставки в отсортированный массив без повторов.

Приём: lower bound (нижняя граница) — первый индекс, где nums[i] >= target.
Аналог: LeetCode 35.
"""


def find_the_insertion_index(nums: list[int], target: int) -> int:
    """Индекс target, а если его нет — место, куда его надо вставить.

    Время O(log n), память O(1).
    """
    # hi = len(nums), а не len(nums) - 1: ответ «вставить в самый конец»
    # тоже законный, значит, он обязан лежать внутри диапазона поиска.
    lo, hi = 0, len(nums)
    while lo < hi:
        mid = (lo + hi) // 2
        if nums[mid] >= target:
            # mid сам может быть ответом — выбрасывать его нельзя.
            hi = mid
        else:
            # mid точно не ответ: всё до него включительно меньше target.
            lo = mid + 1
    # Отдельная ветка «нашли target» не нужна: если target есть в массиве,
    # первый элемент >= target — это он сам.
    return lo
