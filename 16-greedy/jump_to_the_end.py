"""Можно ли допрыгать до последнего индекса.

Приём: frontier tracking (граница достижимого) — жадно поддерживаем одно число,
самый дальний индекс, до которого вообще можно добраться.
Аналог: LeetCode 55 (Jump Game).
"""


def jump_to_the_end(nums: list[int]) -> bool:
    """Вернуть True, если из индекса 0 можно добраться до последнего.

    nums[i] — максимальная длина прыжка из i, числа неотрицательные.
    По условию массив непустой; для пустого возвращаем True (идти некуда).

    Время O(n), память O(1).
    """
    last = len(nums) - 1
    farthest = 0  # всё от 0 до farthest включительно достижимо
    for index, reach in enumerate(nums):
        if index > farthest:
            # Достижимые индексы образуют сплошной префикс. Раз index в него
            # не попал, то и всё, что правее, недостижимо: перепрыгнуть
            # «дыру» можно только с индекса, стоящего до неё.
            return False
        farthest = max(farthest, index + reach)
        if farthest >= last:
            # Дальше смотреть незачем: префикс уже накрыл финиш.
            return True
    return True


def jump_to_the_end_backward(nums: list[int]) -> bool:
    """То же самое, но справа налево: «подтягиваем финиш» к началу.

    goal — самый левый индекс, из которого финиш точно достижим. Если из i
    можно допрыгнуть до goal, то i сам становится новой целью.

    Время O(n), память O(1).
    """
    if not nums:
        return True
    goal = len(nums) - 1
    for index in range(len(nums) - 2, -1, -1):
        if index + nums[index] >= goal:
            # Брать ближайшую цель выгодно: до более левой цели допрыгнуть
            # не сложнее, чем до любой более правой.
            goal = index
    return goal == 0
