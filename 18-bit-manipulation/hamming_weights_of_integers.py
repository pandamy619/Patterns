"""Веса Хэмминга всех чисел от 0 до n.

Вес Хэмминга — количество единичных битов в двоичной записи числа.
Два решения: честный подсчёт по битам для каждого числа и DP, где ответ
для x собирается из уже известного ответа для x >> 1.
Аналог: LeetCode 338.
"""


def count_set_bits(x: int) -> int:
    """Количество единичных битов в неотрицательном x.

    Время O(log x) — по шагу на каждый разряд, память O(1).
    """
    if x < 0:
        # У отрицательного числа в Python «бесконечно много» единиц слева,
        # и цикл со сдвигом вправо никогда не дошёл бы до нуля.
        raise ValueError("x должен быть неотрицательным")
    ones = 0
    while x:
        ones += x & 1  # младший бит — это и есть остаток от деления на 2
        x >>= 1        # выбрасываем его и смотрим на следующий
    return ones


def count_set_bits_kernighan(x: int) -> int:
    """То же, но за число шагов, равное количеству единиц, а не разрядов.

    Время O(k), где k — ответ; память O(1).
    """
    if x < 0:
        raise ValueError("x должен быть неотрицательным")
    ones = 0
    while x:
        # x - 1 превращает младшую единицу в ноль, а нули правее неё —
        # в единицы. Общей частью x и x - 1 остаётся всё, что левее,
        # то есть x без своей младшей единицы.
        x &= x - 1
        ones += 1
    return ones


def hamming_weights_bit_by_bit(n: int) -> list[int]:
    """Веса чисел 0..n, каждое число считается независимо.

    Время O(n log n), память O(1) сверх ответа.
    """
    if n < 0:
        raise ValueError("n должно быть неотрицательным")
    return [count_set_bits(x) for x in range(n + 1)]


def hamming_weights_of_integers(n: int) -> list[int]:
    """Веса чисел 0..n через DP: weights[x] = weights[x >> 1] + (x & 1).

    Время O(n), память O(1) сверх ответа.
    """
    if n < 0:
        raise ValueError("n должно быть неотрицательным")
    weights = [0] * (n + 1)
    for x in range(1, n + 1):
        # x >> 1 — это x без последнего разряда. Оно строго меньше x,
        # значит, его вес уже посчитан; остаётся добавить отброшенный бит.
        weights[x] = weights[x >> 1] + (x & 1)
    return weights
