"""Индекс любого локального максимума; соседние элементы различны.

Приём: lower bound (нижняя граница) по предикату «дальше идёт спуск»:
nums[i] > nums[i + 1]. Массив не отсортирован, но бинарный поиск работает,
потому что мы идём в сторону подъёма, а подъём обязан закончиться вершиной.
Аналог: LeetCode 162.
"""


def local_maxima_in_array(nums: list[int]) -> int:
    """Индекс элемента, который больше обоих соседей (за краями массива — минус бесконечность).

    Время O(log n), память O(1).
    """
    if not nums:
        raise ValueError("в пустом массиве нет локального максимума")

    # Последний индекс входит в диапазон как ответ, но в mid он не попадёт:
    # при lo < hi округление вниз даёт mid < hi, так что nums[mid + 1] существует.
    lo, hi = 0, len(nums) - 1
    while lo < hi:
        mid = (lo + hi) // 2
        if nums[mid] > nums[mid + 1]:
            # Справа спуск: вершина — либо сам mid, либо где-то левее.
            hi = mid
        else:
            # Справа подъём: mid вершиной быть не может, а правее она точно есть.
            lo = mid + 1
    return lo
