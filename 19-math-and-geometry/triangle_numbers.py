"""Сколько троек чисел массива могут быть сторонами невырожденного треугольника.

Приём: сортировка + встречные указатели (inward traversal из темы 01).
Математика здесь в том, что после сортировки из трёх неравенств
треугольника остаётся проверить одно: a + b > c, где c — наибольшая сторона.
Аналог: LeetCode 611.
"""


def triangle_numbers(lengths: list[int]) -> int:
    """Число троек индексов i < j < k, из которых складывается треугольник.

    Тройки различаются индексами: из [2, 2, 2, 2] получится 4 тройки.
    Время O(n²) после сортировки O(n log n), память O(n) на копию.
    """
    sides = sorted(lengths)
    total = 0

    # Перебираем наибольшую сторону, две меньшие ищем слева от неё.
    for largest in range(len(sides) - 1, 1, -1):
        lo, hi = 0, largest - 1
        while lo < hi:
            if sides[lo] + sides[hi] > sides[largest]:
                # Раз хватило даже с самым маленьким lo, хватит и с любым
                # индексом между lo и hi: все они не меньше. Засчитываем
                # разом hi - lo пар и больше к этому hi не возвращаемся.
                total += hi - lo
                hi -= 1
            else:
                # С этим lo не хватает даже при самом большом hi — он бесполезен.
                lo += 1
    return total
