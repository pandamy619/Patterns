"""Одинокое число: все значения встречаются дважды, одно — ровно один раз.

Приём: XOR cancellation (взаимное уничтожение пар). a ^ a = 0 и a ^ 0 = a,
а порядок операндов не важен, поэтому XOR всего массива равен одиночке.
Аналог: LeetCode 136.
"""


def lonely_integer(nums: list[int]) -> int:
    """Вернуть число, у которого нет пары.

    Время O(n), память O(1).
    """
    if not nums:
        raise ValueError("по условию в массиве есть хотя бы один элемент")
    survivor = 0  # 0 — нейтральный элемент XOR, как 0 для сложения
    for value in nums:
        # Второе появление значения гасит первое, где бы в массиве оно
        # ни стояло: XOR коммутативен и ассоциативен.
        survivor ^= value
    return survivor
