"""Задача Иосифа Флавия: кто останется последним в круге.

n человек с номерами 0..n-1 стоят по кругу. Счёт начинается с номера 0,
каждый k-й выбывает, счёт продолжается со следующего. Нужен номер выжившего.

Приём: recurrence (рекуррентное соотношение) — после первого выбывания
остаётся та же задача размера n - 1, только с перенумерацией:
J(1) = 0, J(n) = (J(n - 1) + k) % n.
Аналог: LeetCode 1823 (там нумерация с 1 — к ответу прибавляется единица).
"""


def the_josephus_problem(n: int, k: int) -> int:
    """Рекурсивный вариант — дословная запись формулы.

    Время O(n), память O(n) на стек; при n порядка тысячи упрётся
    в лимит рекурсии Python.
    """
    if n < 1 or k < 1:
        raise ValueError("n и k должны быть положительными")
    if n == 1:
        return 0
    # Первым выбывает (k - 1) % n, новый счёт стартует с k % n. Если
    # в уменьшенном круге выживший имеет номер s (считая от новой точки
    # старта), то в исходном круге это (s + k) % n.
    return (the_josephus_problem(n - 1, k) + k) % n


def the_josephus_problem_iterative(n: int, k: int) -> int:
    """Та же формула снизу вверх: от круга из одного человека к кругу из n.

    Время O(n), память O(1).
    """
    if n < 1 or k < 1:
        raise ValueError("n и k должны быть положительными")
    survivor = 0                          # J(1): в круге один человек
    for size in range(2, n + 1):
        survivor = (survivor + k) % size  # J(size) из J(size - 1)
    return survivor
