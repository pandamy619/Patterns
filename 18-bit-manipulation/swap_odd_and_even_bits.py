"""Поменять местами соседние биты 32-битного беззнакового числа.

Бит 0 меняется с битом 1, бит 2 — с битом 3 и так далее (позиции считаются
от младшего разряда, с нуля).
Приём: parallel masks (групповые маски) — одной маской забираем все чётные
позиции сразу, другой — все нечётные, сдвигаем навстречу и склеиваем.
Аналог: GeeksforGeeks «Swap all odd and even bits».
"""

EVEN_MASK = 0x55555555  # 0101...0101 — единицы на позициях 0, 2, 4, ...
ODD_MASK = 0xAAAAAAAA   # 1010...1010 — единицы на позициях 1, 3, 5, ...
UINT32_MASK = 0xFFFFFFFF


def swap_odd_and_even_bits(n: int) -> int:
    """Вернуть n, в котором каждая пара соседних битов переставлена.

    Время O(1), память O(1): три операции над машинным словом.
    """
    if not 0 <= n <= UINT32_MASK:
        raise ValueError("ожидается беззнаковое 32-битное число")
    even_bits = n & EVEN_MASK  # всё, что стояло на чётных позициях
    odd_bits = n & ODD_MASK    # всё, что стояло на нечётных
    # Чётные уезжают на место нечётных и наоборот. Две половинки не
    # пересекаются ни одним разрядом, поэтому | склеивает их без потерь.
    # Старший чётный бит — 30-й, после сдвига он станет 31-м, так что
    # за 32 разряда результат не вылезет и обрезать его не нужно.
    return (even_bits << 1) | (odd_bits >> 1)


def swap_odd_and_even_bits_naive(n: int) -> int:
    """То же по определению: 16 пар, каждую переставляем отдельно.

    Нужна только как понятный эталон для сравнения. Время O(число битов).
    """
    if not 0 <= n <= UINT32_MASK:
        raise ValueError("ожидается беззнаковое 32-битное число")
    result = 0
    for low in range(0, 32, 2):
        low_bit = (n >> low) & 1
        high_bit = (n >> (low + 1)) & 1
        result |= low_bit << (low + 1)
        result |= high_bit << low
    return result
