"""Сумма на отрезке [i, j] для массива, который не меняется.

Идея: один раз считаем массив префиксных сумм, после чего любой запрос —
разность двух его элементов.
Аналог: LeetCode 303.
"""


class SumBetweenRange:
    """Отвечает на запросы суммы nums[i] + ... + nums[j] (обе границы включены).

    Подготовка O(n) по времени и памяти, каждый запрос — O(1).
    """

    def __init__(self, nums: list[int]) -> None:
        """Построить префиксные суммы. Время O(n), память O(n)."""
        # prefix[t] — сумма первых t элементов, поэтому prefix[0] = 0 («пустой
        # префикс»). Лишняя ячейка в начале избавляет от отдельной ветки
        # для запросов, которые начинаются с индекса 0.
        self._prefix: list[int] = [0]
        for value in nums:
            self._prefix.append(self._prefix[-1] + value)

    def sum_range(self, i: int, j: int) -> int:
        """Вернуть сумму элементов с индексами от i до j включительно.

        Время O(1), память O(1).
        """
        size = len(self._prefix) - 1
        # Проверяем явно: отрицательный индекс Python молча принял бы
        # за отсчёт с конца, и запрос вернул бы правдоподобную чушь.
        if not 0 <= i <= j < size:
            raise IndexError(f"некорректный отрезок [{i}, {j}] для массива длины {size}")
        # Первые j + 1 элементов минус первые i — остаётся ровно отрезок [i, j].
        return self._prefix[j + 1] - self._prefix[i]
