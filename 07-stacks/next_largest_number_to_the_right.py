"""Для каждого элемента — первое большее число справа.

Приём: monotonic stack (монотонный стек). В стеке лежат индексы элементов,
которые ещё не нашли ответ; их значения не возрастают от дна к вершине.
Аналог: LeetCode 496 (ядро той же задачи), родственные — 503 и 739.
"""


def next_largest_number_to_the_right(nums: list[int]) -> list[int]:
    """Вернуть массив, где на месте i стоит первое число правее i, большее nums[i].

    Если такого числа нет, на месте i стоит -1. Равное число «большим» не считается.
    Время O(n): каждый индекс один раз попадает в стек и не более раза его покидает.
    Память O(n).
    """
    answer = [-1] * len(nums)
    unresolved: list[int] = []  # индексы тех, кто ещё ждёт большее число
    for index, value in enumerate(nums):
        # Новое число — ответ для всех ожидающих, кто меньше него. Они лежат
        # на вершине подряд: от дна к вершине значения не возрастают, поэтому
        # первый же «не меньший» означает, что глубже искать незачем.
        while unresolved and nums[unresolved[-1]] < value:
            answer[unresolved.pop()] = value
        unresolved.append(index)
    # Кто остался в стеке — большего справа не дождался, там уже стоит -1.
    return answer
