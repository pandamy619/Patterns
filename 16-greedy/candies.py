"""Минимум конфет для детей в ряду с учётом рейтинга соседей.

Приём: two-pass constraints (два прохода) — ограничение «больше, чем у соседа»
двустороннее; разбиваем его на «левое» и «правое» и удовлетворяем по очереди.
Аналог: LeetCode 135 (Candy).
"""


def distribute_candies(ratings: list[int]) -> list[int]:
    """Вернуть самую экономную раздачу: сколько конфет получит каждый ребёнок.

    Время O(n), память O(n).
    """
    n = len(ratings)
    portions = [1] * n  # правило «каждому хотя бы одна»

    # Проход слева направо закрывает правило только для левого соседа:
    # даём ровно на одну больше — минимум, который ещё не нарушает правило.
    for i in range(1, n):
        if ratings[i] > ratings[i - 1]:
            portions[i] = portions[i - 1] + 1

    # Проход справа налево закрывает правило для правого соседа. max нужен,
    # чтобы не сломать уже выполненное «левое» ограничение: конфеты можно
    # только добавлять, уменьшать нельзя.
    for i in range(n - 2, -1, -1):
        if ratings[i] > ratings[i + 1]:
            portions[i] = max(portions[i], portions[i + 1] + 1)

    return portions


def candies(ratings: list[int]) -> int:
    """Вернуть минимальное общее число конфет.

    Время O(n), память O(n).
    """
    return sum(distribute_candies(ratings))
