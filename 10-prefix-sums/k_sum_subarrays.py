"""Сколько непрерывных подмассивов имеют сумму ровно k.

Числа могут быть отрицательными, поэтому скользящее окно не работает.
Идея: сумма отрезка — разность двух префиксных сумм, а нужный «ранний»
префикс ищем в хеш-таблице частот.
Аналог: LeetCode 560.
"""


def k_sum_subarrays(nums: list[int], k: int) -> int:
    """Вернуть число подмассивов с суммой k.

    Время O(n) в среднем, память O(n).
    """
    # Сколько раз каждая префиксная сумма уже встретилась. Пустой префикс
    # (сумма 0) есть всегда: без него потеряются подмассивы, которые
    # начинаются с индекса 0, — для них «отрезать слева» нужно именно ничего.
    seen: dict[int, int] = {0: 1}

    count = 0
    running = 0
    for value in nums:
        running += value
        # Подмассив, который кончается здесь, имеет сумму k тогда и только
        # тогда, когда слева отрезан префикс с суммой running - k.
        # Таких префиксов может быть несколько — каждый даёт свой подмассив.
        count += seen.get(running - k, 0)
        # Записываем после подсчёта: иначе при k = 0 текущий префикс
        # нашёл бы сам себя и мы посчитали бы пустой подмассив.
        seen[running] = seen.get(running, 0) + 1
    return count


def k_sum_subarrays_quadratic(nums: list[int], k: int) -> int:
    """Промежуточный вариант: массив префиксных сумм + перебор пар границ.

    Время O(n^2), память O(n). Нужен как ступенька к решению с хеш-таблицей:
    видно, что внутренний цикл — это поиск значения среди уже пройденных.
    """
    prefix = [0]
    for value in nums:
        prefix.append(prefix[-1] + value)

    count = 0
    for end in range(1, len(prefix)):
        # Этот цикл — поиск «сколько раз слева встретилось prefix[end] - k».
        # Именно его и заменяет хеш-таблица в основном решении.
        for start in range(end):
            if prefix[end] - prefix[start] == k:
                count += 1
    return count
