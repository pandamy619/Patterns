"""Удалять пары одинаковых соседних букв, пока такие пары есть.

Приём: matching pairs (парные элементы) — стек хранит уже «очищенный»
префикс; новая буква либо аннигилирует с вершиной, либо ложится сверху.
Аналог: LeetCode 1047.
"""


def repeated_removal_of_adjacent_duplicates(text: str) -> str:
    """Вернуть строку, которая останется после всех возможных удалений пар.

    Время O(n), память O(n).
    """
    kept: list[str] = []  # префикс, в котором одинаковых соседей уже нет
    for symbol in text:
        if kept and kept[-1] == symbol:
            # Пара исчезает, и соседом следующей буквы становится то, что
            # лежало под вершиной, — ровно как в строке после удаления.
            kept.pop()
        else:
            kept.append(symbol)
    return "".join(kept)
