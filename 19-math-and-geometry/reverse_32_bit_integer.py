"""Развернуть цифры знакового 32-битного числа, при переполнении вернуть 0.

Приём: overflow guard (проверка переполнения заранее) — сравниваем
с границей, делённой на 10, ДО умножения, поэтому ни одно промежуточное
значение не выходит за 32 бита. В Python целые безразмерны, но решение
написано так, будто это не так: иначе задача теряет смысл.
Аналог: LeetCode 7.
"""

INT_MAX = 2**31 - 1   #  2 147 483 647
INT_MIN = -(2**31)    # -2 147 483 648

# Границы без последней цифры. Написаны числами, а не через //:
# в Python INT_MIN // 10 округлится вниз и даст -214748365.
_MAX_PREFIX, _MAX_LAST = 214_748_364, 7
_MIN_PREFIX, _MIN_LAST = -214_748_364, -8


def _split_last_digit(n: int) -> tuple[int, int]:
    """Вернуть (n без последней цифры, последняя цифра) с усечением к нулю.

    Для отрицательных чисел цифра тоже отрицательная: -47 -> (-4, -7).
    """
    digit = n % 10
    # В Python остаток берёт знак делителя: -47 % 10 == 3, а не -7.
    # Возвращаем его к «сишному» виду.
    if n < 0 and digit > 0:
        digit -= 10
    # n - digit делится на 10 нацело, так что // здесь ничего не округляет.
    # Вычитание безопасно: оно приближает n к нулю.
    return (n - digit) // 10, digit


def reverse_32_bit_integer(n: int) -> int:
    """Число с цифрами n в обратном порядке (знак сохраняется) или 0.

    Время O(log n) — по числу цифр, память O(1).
    """
    reversed_n = 0
    while n != 0:
        n, digit = _split_last_digit(n)

        # Хотим сделать reversed_n * 10 + digit. Проверяем, влезет ли
        # результат, не вычисляя его.
        if reversed_n > _MAX_PREFIX or (reversed_n == _MAX_PREFIX and digit > _MAX_LAST):
            return 0
        if reversed_n < _MIN_PREFIX or (reversed_n == _MIN_PREFIX and digit < _MIN_LAST):
            return 0

        # Знак отдельно не храним: у отрицательного n все цифры
        # отрицательные, и результат сам накапливается с минусом.
        # Заодно не нужен abs(n), который для INT_MIN не влезает в 32 бита.
        reversed_n = reversed_n * 10 + digit
    return reversed_n
