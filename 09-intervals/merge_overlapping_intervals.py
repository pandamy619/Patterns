"""Слить пересекающиеся интервалы.

Приём: sort by start + merge with last (сортировка по началу и слияние
с последним интервалом ответа).
Интервалы закрытые: [1, 4] и [4, 6] имеют общую точку 4 и сливаются в [1, 6].
Аналог: LeetCode 56.
"""


def merge_overlapping_intervals(intervals: list[list[int]]) -> list[list[int]]:
    """Вернуть попарно непересекающиеся интервалы, покрывающие то же множество точек.

    Вход не изменяется, ответ отсортирован по началу.
    Время O(n log n) из-за сортировки, память O(n) на отсортированную копию и ответ.
    """
    merged: list[list[int]] = []
    # После сортировки по началу кандидат на слияние всегда один —
    # последний интервал ответа: у всех предыдущих конец ещё левее.
    for start, end in sorted(intervals):
        if merged and start <= merged[-1][1]:
            # max обязателен: новый интервал может целиком лежать внутри
            # текущего, и тогда его конец правую границу не двигает.
            merged[-1][1] = max(merged[-1][1], end)
        else:
            # Копия, а не ссылка на элемент входа: иначе правка merged[-1][1]
            # испортила бы данные вызывающего кода.
            merged.append([start, end])
    return merged
