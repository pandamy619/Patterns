"""Найти все пересечения между двумя списками интервалов.

Каждый список отсортирован по началу и внутри себя не пересекается.
Приём: two pointers over two sorted lists (два указателя по двум
отсортированным спискам) — дальше идёт тот интервал, что раньше закончился.
Интервалы закрытые: [1, 4] и [4, 9] пересекаются в точке [4, 4].
Аналог: LeetCode 986.
"""


def identify_all_interval_overlaps(
    first: list[list[int]], second: list[list[int]]
) -> list[list[int]]:
    """Вернуть все непустые пересечения интервала из first с интервалом из second.

    Ответ отсортирован по началу.
    Время O(n + m), память O(1), не считая ответа.
    """
    overlaps: list[list[int]] = []
    i = j = 0
    while i < len(first) and j < len(second):
        a_start, a_end = first[i]
        b_start, b_end = second[j]

        # Общая часть начинается там, где начались оба, и кончается там,
        # где кончился первый из них. Если получилось lo > hi — общей части нет.
        lo = max(a_start, b_start)
        hi = min(a_end, b_end)
        if lo <= hi:
            overlaps.append([lo, hi])

        # Кто раньше закончился, тот свою роль сыграл: все следующие интервалы
        # другого списка начинаются правее нынешнего, а значит, и правее этого конца.
        # Второй интервал оставляем — он ещё может задеть следующего соседа.
        if a_end < b_end:
            i += 1
        else:
            j += 1
    return overlaps
