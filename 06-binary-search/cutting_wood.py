"""Максимальная высота пилы, при которой срезано не меньше k древесины.

Приём: binary search on the answer (бинарный поиск по ответу) в форме
upper bound (верхняя граница): ищем последнюю высоту, которая ещё подходит.
Аналог: SPOJ EKO; по духу близки LeetCode 875 и 2226.
"""


def cutting_wood(heights: list[int], k: int) -> int:
    """Наибольшая целая H, при которой sum(max(0, h - H)) >= k; -1, если дерева не хватит.

    Время O(n log M), где M — высота самого высокого дерева; память O(1).
    """
    # При H = 0 срезается вообще всё. Если даже этого мало, ответа нет,
    # и это единственный случай, когда верхней границы не существует.
    if sum(heights) < k:
        return -1

    # Ищем не по индексам массива, а по значениям ответа: H от 0 до max.
    # Выше самого высокого дерева пилу поднимать бессмысленно.
    lo, hi = 0, max(heights, default=0)
    while lo < hi:
        mid = (lo + hi + 1) // 2      # lo = mid → округляем вверх
        if _wood_cut(heights, mid) >= k:
            lo = mid                  # mid подходит, но, может быть, можно выше
        else:
            hi = mid - 1              # mid уже не подходит, всё выше — тем более
    return lo


def _wood_cut(heights: list[int], saw: int) -> int:
    """Сколько древесины срежет пила на высоте saw."""
    return sum(tree - saw for tree in heights if tree > saw)
